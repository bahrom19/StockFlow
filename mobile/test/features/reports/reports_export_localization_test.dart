import 'dart:convert';
import 'dart:io';

import 'package:flutter/material.dart';
import 'package:flutter_gen/gen_l10n/app_localizations.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:stockflow/core/utils/pdf_fonts.dart';
import 'package:stockflow/features/dashboard/domain/dashboard_models.dart';
import 'package:stockflow/features/reports/data/report_export.dart';

import '../../helpers/pdf_text.dart';

/// Phase 5D-5 — PDF report export localization.
///
/// Guard 1 (EN contract): the exported report keeps its pre-localization
/// copy byte-for-byte (via getters and the null-l10n fallback).
/// Guard 2: RU/KK get natural translations for every PDF copy string.
/// Guard 3: ARB parity — the new keys exist in all three locales with
/// matching key sets and no duplicates.
AppLocalizations en() => lookupAppLocalizations(const Locale('en'));
AppLocalizations ru() => lookupAppLocalizations(const Locale('ru'));
AppLocalizations kk() => lookupAppLocalizations(const Locale('kk'));

DashboardSummary _summary() => const DashboardSummary(
      todaySales: DaySales(revenue: '1200.00', count: 6),
      yesterdaySales: DaySales(revenue: '900.00', count: 5),
      monthSales: DaySales(revenue: '45000.00', count: 210),
      ordersCount: 210,
      grossRevenue: '45000.00',
      grossProfit: '12000.00',
      inventoryValue: '80000.00',
      lowStockProducts: 3,
      outOfStockProducts: 1,
      customerCount: 12,
      supplierCount: 4,
      purchaseTotal: '25000.00',
    );

List<RecentSale> _sales() => const [
      RecentSale(
        id: 's1',
        saleNumber: 'S-0001',
        createdAt: '2026-08-15',
        status: 'COMPLETED',
        total: '250.00',
        paidAmount: '250.00',
      ),
    ];

void main() {
  // rootBundle asset loading (Roboto TTFs) needs the binding in tests.
  TestWidgetsFlutterBinding.ensureInitialized();

  group('EN byte-for-byte contract — report PDF copy', () {
    test('title, generated, summary, recent sales, footer', () {
      expect(en().reportPdfTitle, 'StockFlow — Business Report');
      expect(en().reportPdfGeneratedAt('2026-08-15 12:00:00.000'),
          'Generated 2026-08-15 12:00:00.000');
      expect(en().reportPdfPerformanceSummary, 'Performance Summary');
      expect(en().recentSales, 'Recent Sales'); // reused, no duplicate key
      expect(en().reportPdfFooter,
          'StockFlow ERP · Generated by the Reports module');
    });

    test('table headers + empty state', () {
      expect(en().reportPdfToday, 'Today');
      expect(en().reportPdfYesterday, 'Yesterday');
      expect(en().reportPdfMonth, 'Month');
      expect(en().reportPdfGrossProfit, 'Gross Profit');
      expect(en().reportPdfInventoryValue, 'Inventory Value');
      expect(en().reportPdfOrders, 'Orders');
      expect(en().reportPdfAvgOrder, 'Avg. Order');
      expect(en().reportPdfNoSalesInPeriod, 'No sales in this period.');
    });
  });

  group('RU / KK translations', () {
    test('RU values are localized, non-empty, and match the template', () {
      expect(ru().reportPdfTitle, 'StockFlow — Бизнес-отчет');
      expect(ru().reportPdfPerformanceSummary, 'Сводка показателей');
      expect(ru().reportPdfFooter,
          'StockFlow ERP · Сформировано модулем отчетов');
      expect(ru().recentSales, 'Последние продажи');
      expect(ru().reportPdfToday, 'Сегодня');
      expect(ru().reportPdfYesterday, 'Вчера');
      expect(ru().reportPdfMonth, 'Месяц');
      expect(ru().reportPdfGrossProfit, 'Валовая прибыль');
      expect(ru().reportPdfInventoryValue, 'Стоимость запасов');
      expect(ru().reportPdfOrders, 'Заказы');
      expect(ru().reportPdfAvgOrder, 'Средний заказ');
      expect(ru().reportPdfNoSalesInPeriod, 'Продаж за этот период нет.');
    });

    test('KK values are localized, non-empty, and match the template', () {
      expect(kk().reportPdfTitle, 'StockFlow — Бизнес-есеп');
      expect(kk().reportPdfPerformanceSummary, 'Көрсеткіштер жиынтығы');
      expect(kk().reportPdfFooter, 'StockFlow ERP · Есептер модулі құрды');
      expect(kk().recentSales, 'Соңғы сатылымдар');
      expect(kk().reportPdfToday, 'Бүгін');
      expect(kk().reportPdfYesterday, 'Кеше');
      expect(kk().reportPdfMonth, 'Ай');
      expect(kk().reportPdfGrossProfit, 'Жалпы пайда');
      expect(kk().reportPdfInventoryValue, 'Қор құны');
      expect(kk().reportPdfOrders, 'Тапсырыстар');
      expect(kk().reportPdfAvgOrder, 'Орташа тапсырыс');
      expect(kk().reportPdfNoSalesInPeriod, 'Бұл кезеңде сатылым жоқ.');
    });

    test('RU/KK never leak the English template in the generated line',
        () {
      // The placeholder must be substituted — no raw "{date}" left behind.
      expect(ru().reportPdfGeneratedAt('15.08.2026'), isNot(contains('{date}')));
      expect(ru().reportPdfGeneratedAt('15.08.2026'), contains('15.08.2026'));
      expect(kk().reportPdfGeneratedAt('15.08.2026'), isNot(contains('{date}')));
      expect(kk().reportPdfGeneratedAt('15.08.2026'), contains('15.08.2026'));
      expect(ru().reportPdfGeneratedAt('x'), isNot(contains('Generated ')));
      expect(kk().reportPdfGeneratedAt('x'), isNot(contains('Generated ')));
    });

    test('placeholder is substituted in all locales (no raw {date})', () {
      // Generated output never leaks the raw placeholder...
      expect(en().reportPdfGeneratedAt('2026-08-15'), isNot(contains('{date}')));
      expect(ru().reportPdfGeneratedAt('15.08.2026'), isNot(contains('{date}')));
      expect(kk().reportPdfGeneratedAt('15.08.2026'), isNot(contains('{date}')));
      // ...and the argument is rendered.
      expect(en().reportPdfGeneratedAt('2026-08-15'), contains('2026-08-15'));
      expect(ru().reportPdfGeneratedAt('15.08.2026'), contains('15.08.2026'));
      expect(kk().reportPdfGeneratedAt('15.08.2026'), contains('15.08.2026'));
    });
  });

  group('buildPdf localization path', () {
    test('null l10n falls back to EN byte-for-byte and still builds',
        () async {
      final bytes = await ReportExport.buildPdf(
        summary: _summary(),
        sales: _sales(),
        generatedAt: DateTime.utc(2026, 8, 15, 12),
      );
      expect(bytes.length, greaterThan(1000));
    });

    test('builds with EN/RU/KK AppLocalizations', () async {
      for (final loc in [en(), ru(), kk()]) {
        final bytes = await ReportExport.buildPdf(
          summary: _summary(),
          sales: _sales(),
          generatedAt: DateTime.utc(2026, 8, 15, 12),
          l10n: loc,
        );
        expect(bytes.length, greaterThan(1000),
            reason: '${loc.localeName} PDF renders non-trivial output');
      }
    });
  });

  group('PDF text extraction — Unicode glyphs actually render (5D-6)', () {
    test('EN PDF text is intact and byte-for-byte', () async {
      final bytes = await ReportExport.buildPdf(
        summary: _summary(),
        sales: const [],
        generatedAt: DateTime.utc(2026, 8, 15, 12),
        l10n: en(),
      );
      final text = extractPdfText(bytes);
      expect(text, contains('StockFlow'));
      expect(text, contains('Business Report'));
      expect(text, contains('Performance Summary'));
      expect(text, contains('Generated 2026-08-15'));
      expect(text, contains('Today'));
      expect(text, contains('Gross Profit'));
      expect(text, contains('Inventory Value'));
      expect(text, contains('Avg. Order'));
      expect(text, contains('Recent Sales'));
      expect(text, contains('Number'));
      expect(text, contains('Date'));
      expect(text, contains('Status'));
      expect(text, contains('Total'));
      expect(text, contains('Paid'));
      expect(text, contains('No sales in this period.'));
      expect(text, contains('Generated by the Reports module'));
    });

    test('RU PDF contains Cyrillic content + localized headers', () async {
      final bytes = await ReportExport.buildPdf(
        summary: _summary(),
        sales: const [],
        generatedAt: DateTime.utc(2026, 8, 15, 12),
        l10n: ru(),
      );
      final text = extractPdfText(bytes);
      expect(text, contains('Бизнес-отчет'));
      expect(text, contains('Сформировано 2026-08-15'));
      expect(text, contains('Сводка показателей'));
      expect(text, contains('Сегодня'));
      expect(text, contains('Валовая прибыль'));
      expect(text, contains('Стоимость запасов'));
      expect(text, contains('Средний заказ'));
      expect(text, contains('Последние продажи'));
      expect(text, contains('Номер'));
      expect(text, contains('Дата'));
      expect(text, contains('Статус'));
      expect(text, contains('Итого'));
      expect(text, contains('Оплачено'));
      expect(text, contains('этот период нет'));
      expect(text, contains('Сформировано модулем отчетов'));
    });

    test('KK PDF contains Kazakh content + localized headers', () async {
      final bytes = await ReportExport.buildPdf(
        summary: _summary(),
        sales: const [],
        generatedAt: DateTime.utc(2026, 8, 15, 12),
        l10n: kk(),
      );
      final text = extractPdfText(bytes);
      expect(text, contains('Бизнес-есеп'));
      expect(text, contains('Құрылған 2026-08-15'));
      expect(text, contains('Көрсеткіштер жиынтығы'));
      expect(text, contains('Бүгін'));
      expect(text, contains('Жалпы пайда'));
      expect(text, contains('Қор құны'));
      expect(text, contains('Орташа тапсырыс'));
      expect(text, contains('Соңғы сатылымдар'));
      expect(text, contains('Нөмір'));
      expect(text, contains('Күні'));
      expect(text, contains('Мәртебе'));
      expect(text, contains('Барлығы'));
      expect(text, contains('Төленді'));
      expect(text, contains('кезеңде сатылым жоқ'));
      expect(text, contains('Есептер модулі құрды'));
    });

    test('the full Kazakh alphabet survives PDF generation', () async {
      await PdfFonts.ensureLoaded();
      final doc = pw.Document();
      doc.addPage(pw.Page(
        pageFormat: PdfPageFormat.a4,
        build: (_) => pw.Text(
          'Әә Ғғ Ққ Ңң Өө Ұұ Үү Һһ Іі',
          style: pw.TextStyle(font: PdfFonts.regular, fontSize: 12),
        ),
      ));
      final text = extractPdfText(await doc.save());
      for (final ch in 'Әә Ғғ Ққ Ңң Өө Ұұ Үү Һһ Іі'.split('')) {
        expect(text, contains(ch), reason: 'Kazakh glyph $ch missing from PDF');
      }
    });
  });

  group('ARB parity — no duplicate/new-key drift', () {
    Map<String, dynamic> arb(String file) =>
        jsonDecode(File('lib/l10n/$file').readAsStringSync())
            as Map<String, dynamic>;

    test('EN/RU/KK have identical key sets', () {
      final enKeys = arb('app_en.arb').keys.toSet();
      final ruKeys = arb('app_ru.arb').keys.toSet();
      final kkKeys = arb('app_kk.arb').keys.toSet();
      expect(ruKeys.difference(enKeys), isEmpty, reason: 'RU keys missing in EN');
      expect(kkKeys.difference(enKeys), isEmpty, reason: 'KK keys missing in EN');
      expect(enKeys.difference(ruKeys), isEmpty, reason: 'EN keys missing in RU');
      expect(enKeys.difference(kkKeys), isEmpty, reason: 'EN keys missing in KK');
    });

    test('the 5D-5 keys exist in all locales', () {
      for (final file in ['app_en.arb', 'app_ru.arb', 'app_kk.arb']) {
        final d = arb(file);
        for (final key in [
          'reportPdfTitle',
          'reportPdfGeneratedAt',
          'reportPdfPerformanceSummary',
          'reportPdfFooter',
          'reportPdfToday',
          'reportPdfYesterday',
          'reportPdfMonth',
          'reportPdfGrossProfit',
          'reportPdfInventoryValue',
          'reportPdfOrders',
          'reportPdfAvgOrder',
          'reportPdfNoSalesInPeriod',
          'recentSales', // reused — must still exist
        ]) {
          expect(d.containsKey(key), isTrue,
              reason: '$key missing in $file');
        }
      }
    });

    test('new keys are non-empty in every locale', () {
      for (final file in ['app_en.arb', 'app_ru.arb', 'app_kk.arb']) {
        final d = arb(file);
        for (final key in [
          'reportPdfTitle',
          'reportPdfGeneratedAt',
          'reportPdfPerformanceSummary',
          'reportPdfFooter',
          'reportPdfToday',
          'reportPdfYesterday',
          'reportPdfMonth',
          'reportPdfGrossProfit',
          'reportPdfInventoryValue',
          'reportPdfOrders',
          'reportPdfAvgOrder',
          'reportPdfNoSalesInPeriod',
        ]) {
          final v = d[key] as String;
          expect(v.trim(), isNotEmpty, reason: '$key empty in $file');
        }
      }
    });

    test('reportPdfGeneratedAt keeps the {date} placeholder in every ARB', () {
      // The template in the ARB file must declare the placeholder so the
      // generated getter substitutes it.
      for (final file in ['app_en.arb', 'app_ru.arb', 'app_kk.arb']) {
        final v = arb(file)['reportPdfGeneratedAt'] as String;
        expect(v, contains('{date}'), reason: 'placeholder missing in $file');
      }
    });
  });
}
